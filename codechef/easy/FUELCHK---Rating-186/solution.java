import java.util.*;
import java.lang.*;
import java.io.*;

class Codechef
{
	public static void main (String[] args) throws java.lang.Exception
	{
		Scanner sc=new Scanner(System.in);
		int x=sc.nextInt();
		int y=sc.nextInt();
		int t=x*y;
		if(t>=100){
		    System.out.println("Yes");
		}
		else{
		    System.out.println("No");
		}

	}
}
